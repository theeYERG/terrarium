import { chromium } from 'playwright';
const browser = await chromium.launch({ channel: 'chrome', headless: true, args: ['--use-angle=d3d11', '--enable-gpu'] });
const page = await browser.newPage({ viewport: { width: 1280, height: 800 } });
await page.goto('http://localhost:5179/');
await page.waitForFunction(() => window.__terrarium?.ready, null, { timeout: 90000 });
await page.evaluate(() => window.__terrarium.start());
await page.waitForTimeout(1500);
const count = () => page.evaluate(() => { const T = window.__terrarium.chunks; let n = 0; for (let i = 0; i < T.mats.length; i++) if (T.mats[i] && T.mats[i] !== 6 && T.fills[i] >= 128) n++; return n; });
const a = await count();
await page.evaluate(() => { const T = window.__terrarium; T.send({ t: 'snapshot' }); for (let k = 0; k < 8; k++) T.apply({ tool: 'dig', mat: 0, x: 64, y: 40 - k, z: 64, nx: 0, ny: 1, nz: 0, r: 5 }); });
await page.waitForTimeout(1000);
const b1 = await count();
await page.waitForTimeout(3000);
const b = await count();
console.log('after dig 1s', b1);
await page.keyboard.press('Control+z');
await page.waitForTimeout(3000);
const c = await count();
console.log({ before: a, afterDig: b, afterUndo: c, undoDepth: await page.evaluate(() => window.__terrarium.undoDepth) });
await browser.close();
