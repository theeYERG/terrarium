// Screenshot tour for art review: node tests/look.mjs [url]
import { chromium } from 'playwright';
const url = process.argv[2] || 'http://localhost:5179/';
const browser = await chromium.launch({ channel: 'chrome', headless: true, args: ['--use-angle=d3d11', '--enable-gpu', '--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
await page.goto(url);
await page.waitForFunction(() => window.__terrarium?.ready, null, { timeout: 90000 });
await page.evaluate(() => window.__terrarium.start());
await page.waitForTimeout(1500);
await page.evaluate(() => { document.getElementById('hud').classList.add('faded'); window.__terrarium.sky.running = false; });
const look = (x, y, z, tx, ty, tz, time = 0.36) => page.evaluate(([x, y, z, tx, ty, tz, time]) => { const T = window.__terrarium; T.sky.time = time; T.look(x, y, z, tx, ty, tz); }, [x, y, z, tx, ty, tz, time]);
const info = await page.evaluate(() => window.__terrarium.info);
const [lx, , lz] = info.lake; const [fx, , fz] = info.waterfall; const [mx, , mz] = info.mountain;
const a = Math.atan2(lz - 64, lx - 64) + 0.45;
await look(64 + Math.cos(a) * 125, 92, 64 + Math.sin(a) * 125, 64, 32, 64); await page.waitForTimeout(2000);
await page.screenshot({ path: 'shots/look-hero.png' });
const dx = fx - 64, dz = fz - 64, l = Math.hypot(dx, dz);
await look(fx + dx / l * 30 - dz / l * 28, 30, fz + dz / l * 30 + dx / l * 28, fx, 24, fz); await page.waitForTimeout(2500);
await page.screenshot({ path: 'shots/look-waterfall.png' });
await look(mx + 30, 62, mz + 30, mx, 46, mz); await page.waitForTimeout(1500);
await page.screenshot({ path: 'shots/look-peak.png' });
await page.evaluate(([x, z]) => { for (let k = 0; k < 30; k++) window.__terrarium.apply({ tool: 'pour', mat: 4, x, y: 38, z, nx: 0, ny: 1, nz: 0, r: 3 }); }, [64, 70]);
await look(64 + 22, 50, 70 + 22, 64, 37, 70); await page.waitForTimeout(1500);
await page.screenshot({ path: 'shots/look-sandpour.png' });
await page.waitForTimeout(6000);
await page.screenshot({ path: 'shots/look-sandpile.png' });
await look(64 + Math.cos(a) * 125, 92, 64 + Math.sin(a) * 125, 64, 32, 64, 0.72); await page.waitForTimeout(2000);
await page.screenshot({ path: 'shots/look-sunset.png' });
await look(64 + Math.cos(a) * 125, 92, 64 + Math.sin(a) * 125, 64, 32, 64, 0.0); await page.waitForTimeout(2000);
await page.screenshot({ path: 'shots/look-night.png' });
await browser.close();
