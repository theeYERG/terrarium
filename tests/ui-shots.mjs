// Screenshots of UI states: node tests/ui-shots.mjs
import { chromium } from 'playwright';
const browser = await chromium.launch({ channel: 'chrome', headless: true, args: ['--use-angle=d3d11', '--enable-gpu', '--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
await page.goto('http://localhost:5179/');
await page.waitForTimeout(400);
await page.screenshot({ path: 'shots/ui-title-loading.png' });
await page.waitForFunction(() => window.__terrarium?.ready);
await page.waitForTimeout(500);
await page.screenshot({ path: 'shots/ui-title.png' });
await page.click('#enter');
await page.waitForTimeout(1500);
await page.keyboard.press('?');
await page.waitForTimeout(300);
await page.screenshot({ path: 'shots/ui-help.png' });
await page.keyboard.press('Escape');
await page.click('#topbar button:nth-child(16)'); // settings
await page.waitForTimeout(300);
await page.screenshot({ path: 'shots/ui-settings.png' });
await page.keyboard.press('Escape');
await page.mouse.click(5, 450);
await page.keyboard.press('i');
await page.keyboard.press('f');
await page.mouse.move(720, 500);
await page.waitForTimeout(800);
await page.mouse.move(722, 502);
await page.waitForTimeout(500);
await page.screenshot({ path: 'shots/ui-inspect.png' });
await page.hover('#palette .swatch:nth-child(5)');
await page.waitForTimeout(300);
await page.screenshot({ path: 'shots/ui-tooltip.png' });
await page.evaluate(() => { const s = window.__terrarium.sky; s.running = false; s.time = 0.0; });
await page.mouse.move(5, 450);
await page.waitForTimeout(1500);
await page.screenshot({ path: 'shots/ui-night.png' });
await page.evaluate(() => { const s = window.__terrarium.sky; s.time = 0.73; });
await page.waitForTimeout(1500);
await page.screenshot({ path: 'shots/ui-sunset.png' });
await browser.close();
